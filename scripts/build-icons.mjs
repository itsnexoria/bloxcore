// Builds js/lucide-lite.js — a drop-in replacement for the full Lucide icon library (~420 KB) containing only
// the icons the site actually uses (usually ~40 KB). Same createIcons() behaviour as lucide@1.34.0, and if a page ever
// asks for an icon that is not in the bundle it lazy-loads the full library once as a fallback, so nothing breaks.
//
// Run after adding new icons:   npm i -D lucide@1.34.0 && node scripts/build-icons.mjs
// What counts as "used": every data-lucide="…" in HTML/JS, plus any string literal in HTML/JS/MJS that is exactly a
// Lucide icon name (catches icons picked dynamically, e.g. { icon: 'trophy' }), plus EXTRA (icon names stored in the DB).
import fs from 'node:fs';
import path from 'node:path';
import { icons } from 'lucide';

const ROOT = process.argv[2] || '.';
const OUT = path.join(ROOT, 'js/lucide-lite.js');
const EXTRA = ['crosshair', 'flame', 'handshake', 'message-circle', 'repeat', 'shield', 'swords', 'thumbs-up', 'trending-up', 'user-plus', 'citrus', 'gem', 'hand', 'shapes', 'shirt', 'sword', 'ticket', 'user', 'package', 'copy', 'check', 'x'];
const toKebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Za-z])([0-9])/g, '$1-$2').replace(/([0-9])([A-Za-z])/g, '$1-$2').toLowerCase();
const toPascal = (s) => s.replace(/^([A-Z])|[\s-_]+(\w)/g, (m, a, b) => (b ? b.toUpperCase() : a.toUpperCase())).replace(/^[a-z]/, (c) => c.toUpperCase());

const known = new Map(); // kebab name -> iconNode
for (const [pascal, node] of Object.entries(icons)) known.set(toKebab(pascal), node);

const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (['node_modules', '.git', 'patches'].includes(e.name)) continue;
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(html|js|mjs)$/.test(e.name) && e.name !== 'lucide-lite.js') files.push(p);
  }
})(ROOT);

const used = new Set(EXTRA);
for (const f of files) {
  const t = fs.readFileSync(f, 'utf8');
  for (const m of t.matchAll(/data-lucide=\\?["']([a-z0-9-]+)\\?["']/g)) used.add(m[1]);
  if (!f.endsWith('.html')) for (const m of t.matchAll(/['"`]([a-z][a-z0-9-]{1,40})['"`]/g)) if (known.has(m[1])) used.add(m[1]);
}
// literal names inside HTML inline scripts too
for (const f of files.filter((x) => x.endsWith('.html'))) {
  const t = fs.readFileSync(f, 'utf8');
  for (const s of t.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) for (const m of s[1].matchAll(/['"`]([a-z][a-z0-9-]{1,40})['"`]/g)) if (known.has(m[1])) used.add(m[1]);
}

const bundle = {};
const missing = [];
for (const n of [...used].sort()) { if (known.has(n)) bundle[n] = known.get(n); else missing.push(n); }
// data-lucide names that are not real icons are ignored (they would not render with the full library either)

const code = `/* lucide-lite — generated by scripts/build-icons.mjs (lucide@1.34.0 subset, ${Object.keys(bundle).length} icons). Do not edit. */
(function () {
  var ICONS = ${JSON.stringify(bundle)};
  var FULL = 'https://unpkg.com/lucide@1.34.0';
  var D = { xmlns: 'http://www.w3.org/2000/svg', width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round' };
  var NS = 'http://www.w3.org/2000/svg';
  var loadingFull = false;
  function node(n) {
    var el = document.createElementNS(NS, n[0]);
    for (var k in n[1]) el.setAttribute(k, String(n[1][k]));
    if (n[2] && n[2].length) n[2].forEach(function (c) { el.appendChild(node(c)); });
    return el;
  }
  function hasA11y(a) { return a['aria-label'] !== undefined || a['aria-labelledby'] !== undefined || a.role !== undefined || a.title !== undefined; }
  function loadFull() {
    if (loadingFull) return; loadingFull = true;
    var s = document.createElement('script'); s.src = FULL;
    s.onload = function () { if (window.lucide && window.lucide.createIcons && window.lucide !== api) window.lucide.createIcons(); };
    document.head.appendChild(s);
  }
  function createIcons(opts) {
    opts = opts || {};
    var nameAttr = opts.nameAttr || 'data-lucide', extra = opts.attrs || {}, root = opts.root || document;
    var els = root.querySelectorAll('[' + nameAttr + ']'), needFull = false;
    Array.prototype.slice.call(els).forEach(function (el) {
      var name = el.getAttribute(nameAttr), icon = ICONS[name];
      if (!icon) { needFull = true; return; }
      var attrs = {}; Array.prototype.forEach.call(el.attributes, function (a) { attrs[a.name] = a.value; });
      var all = {}, k;
      for (k in D) all[k] = D[k];
      all['data-lucide'] = name;
      if (!hasA11y(attrs)) all['aria-hidden'] = 'true';
      for (k in extra) all[k] = extra[k];
      for (k in attrs) all[k] = attrs[k];
      var cls = ['lucide', 'lucide-' + name].concat(attrs['class'] ? attrs['class'].split(' ') : [], extra['class'] ? String(extra['class']).split(' ') : []).filter(Boolean).filter(function (c, i, a) { return a.indexOf(c) === i; }).join(' ');
      if (cls) all['class'] = cls;
      var svg = document.createElementNS(NS, 'svg');
      for (k in all) svg.setAttribute(k, String(all[k]));
      icon.forEach(function (c) { svg.appendChild(node(c)); });
      if (el.parentNode) el.parentNode.replaceChild(svg, el);
    });
    if (needFull) loadFull(); // an icon outside the bundle: fetch the full library once and let it finish the job
  }
  var api = { createIcons: createIcons, icons: ICONS };
  window.lucide = api;
})();
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, code);
console.log(`lucide-lite: ${Object.keys(bundle).length} icons, ${(Buffer.byteLength(code) / 1024).toFixed(1)} KB (full library: ~410 KB)`);
if (missing.length) console.log(`ignored names that are not Lucide icons: ${missing.join(', ')}`);
